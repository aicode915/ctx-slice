import path from 'node:path';
import { DependencyNode, OutputFormat } from '../types.js';

export function generateTopologyTree(nodes: DependencyNode[], entryPaths: string[]): string {
  const nodeByAbs = new Map(nodes.map(n => [n.absolutePath, n]));
  const lines: string[] = ['Dependency Topology:'];

  const visitedInTree = new Set<string>();

  function printBranch(absPath: string, prefix: string, isLast: boolean) {
    const node = nodeByAbs.get(absPath);
    if (!node) return;

    const branch = isLast ? '└── ' : '├── ';
    const tag = node.depth === 0 ? ' [ENTRY]' : node.isSkeleton ? ' [SKELETON]' : ' [FULL]';
    lines.push(`${prefix}${branch}${node.filePath}${tag}`);

    if (visitedInTree.has(absPath)) return;
    visitedInTree.add(absPath);

    const childPrefix = prefix + (isLast ? '    ' : '│   ');
    const localDeps = node.dependencies.filter(dep => nodeByAbs.has(dep));

    localDeps.forEach((dep, idx) => {
      printBranch(dep, childPrefix, idx === localDeps.length - 1);
    });
  }

  entryPaths.forEach((entry, idx) => {
    printBranch(entry, '', idx === entryPaths.length - 1);
  });

  return lines.join('\n');
}

export function formatOutput(
  nodes: DependencyNode[],
  topologyTree: string,
  format: OutputFormat
): string {
  if (format === 'json') {
    return JSON.stringify(
      {
        topology: topologyTree,
        files: nodes.map(n => ({
          path: n.filePath,
          depth: n.depth,
          isSkeleton: n.isSkeleton,
          tokens: n.tokenCount,
          content: n.processedContent
        }))
      },
      null,
      2
    );
  }

  if (format === 'xml') {
    const parts: string[] = [];
    parts.push('<codebase_slice>');
    parts.push('  <topology>');
    parts.push(`<![CDATA[\n${topologyTree}\n]]>`);
    parts.push('  </topology>');
    parts.push('  <files>');
    for (const node of nodes) {
      const mode = node.isSkeleton ? 'skeleton' : 'full';
      parts.push(`    <file path="${node.filePath}" depth="${node.depth}" mode="${mode}" tokens="${node.tokenCount}">`);
      parts.push(`<![CDATA[\n${node.processedContent}\n]]>`);
      parts.push('    </file>');
    }
    parts.push('  </files>');
    parts.push('</codebase_slice>');
    return parts.join('\n');
  }

  // Default: Markdown
  const mdParts: string[] = [];
  mdParts.push('# Codebase Context Slice');
  mdParts.push('\n> Generated by [ctx-slice](https://github.com/liukun/ctx-slice) for LLM prompts.');
  mdParts.push('\n```text');
  mdParts.push(topologyTree);
  mdParts.push('```\n');

  for (const node of nodes) {
    const lang = detectLanguage(node.filePath);
    const badge = node.isSkeleton ? '🧩 *(AST Skeleton / Signatures Only)*' : '📄 *(Full Source)*';
    mdParts.push(`## \`${node.filePath}\` (Depth: ${node.depth}) ${badge}\n`);
    mdParts.push('```' + lang);
    mdParts.push(node.processedContent);
    mdParts.push('```\n');
  }

  return mdParts.join('\n');
}

function detectLanguage(filePath: string): string {
  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case '.ts':
      return 'typescript';
    case '.tsx':
      return 'tsx';
    case '.js':
    case '.mjs':
    case '.cjs':
      return 'javascript';
    case '.jsx':
      return 'jsx';
    case '.py':
      return 'python';
    case '.json':
      return 'json';
    case '.go':
      return 'go';
    case '.rs':
      return 'rust';
    default:
      return '';
  }
}
